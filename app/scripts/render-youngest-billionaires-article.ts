// Writes growth/money/youngest-billionaires/ARTICLE.md from the draft copy module,
// so the CMS hand-off text and the Preview route never drift apart.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { youngestBillionairesArticle as a } from "../src/lib/youngest-billionaires-article";
import {
  youngestBillionaires as data,
  billions,
} from "../src/lib/youngest-billionaires";

const site = (text: string) =>
  text.replace(/\]\(\//g, "](https://visionarytalks.com/");
const table = [
  "| Rank | Name | Age | Net worth (USD B) | Source of wealth | Country | Inherited or self-made |",
  "|---|---|---|---|---|---|---|",
  ...data.people.map(
    (p) =>
      `| ${p.rank} | ${p.name} | ${p.age} | ${billions(p.netWorthUSD_B)} | ${p.sourceOfWealth} | ${p.citizenship} | ${p.selfMade ? "Self-made" : "Inherited"} |`,
  ),
  "",
  "As of 1 March 2026, Forbes. Ties at the same age are ordered as in the data.",
].join("\n");
const map = [
  "[Interactive component: WorldBillionaireMap, under-30 billionaires by citizenship, as of 1 March 2026]",
  "",
  ...data.byCountry.map((c) => `- ${c.country}: ${c.count}`),
].join("\n");
const body = a.blocks
  .map((b) => {
    if (b.type === "p") return site(b.text);
    if (b.type === "h2") return `## ${b.text}`;
    if (b.type === "ol")
      return b.items.map((x, i) => `${i + 1}. ${site(x)}`).join("\n");
    if (b.type === "ul") return b.items.map((x) => `- ${site(x)}`).join("\n");
    if (b.type === "map") return map;
    return (
      "[Interactive component: YoungestBillionairesRanking, sortable]\n\n" +
      table
    );
  })
  .join("\n\n");
const sources = a.sources
  .map(
    (s) =>
      `- [${s.title}](${s.url}), ${s.publisher}, ${s.publishedAt}. ${s.evidence}`,
  )
  .join("\n");
const out = fileURLToPath(
  new URL(
    "../../growth/money/youngest-billionaires/ARTICLE.md",
    import.meta.url,
  ),
);
writeFileSync(
  out,
  `<!-- Generated by app/scripts/render-youngest-billionaires-article.ts from app/src/lib/youngest-billionaires-article.ts. Edit the module, not this file. -->\n\n` +
    `# ${a.title}\n\n` +
    `Status: DRAFT, Preview only. Not published. Path: ${a.path}\n\n` +
    `SEO title: ${a.seoTitle}\n\nMeta description: ${a.description}\n\n` +
    `By Daniel Mercer\n\n_${a.dek}_\n\n${body}\n\n## Sources\n\n${sources}\n`,
);
console.log("Wrote " + out);
